const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const scope={view:{extend:x=>x},uci:{},ui:{},network:{}};
vm.runInNewContext('(function(){'+fs.readFileSync('setup-wizard.js','utf8').replace('return view.extend({','globalThis.planSetup=planSetup; return view.extend({')+'})()',scope);
const plan=scope.planSetup;
const base={mode:'bypass',ip:'192.168.11.2',prefix:'24',gateway:'192.168.11.1',dns:'',wan:'eth1',username:'u',password:'p'};
const one={lan:{device:'br-lan'},bridge:{'.name':'br','ports':['eth0']}};
const p=plan(base,one,['eth0']);
assert(p.some(x=>JSON.stringify(x)===JSON.stringify(['set','network','lan','gateway','192.168.11.1'])));
assert(!p.some(x=>x[1]==='network'&&x[2]==='wan'));
assert(p.some(x=>x[1]==='dhcp'&&x[2]==='lan'&&x[3]==='ignore'&&x[4]==='1'));
assert.throws(()=>plan({...base,ip:base.gateway},one,['eth0']),/不能与上级网关相同/);
assert.throws(()=>plan({...base,gateway:'192.168.1.1'},one,['eth0']),/同一子网/);
assert.throws(()=>plan({...base,ip:'192.168.11.0'},one,['eth0']),/主机地址/);
assert.throws(()=>plan({...base,mode:'dhcp',wan:'eth0'},one,['eth0']),/唯一的 LAN/);
assert.throws(()=>plan({...base,mode:'pppoe',password:''},one,['eth0','eth1']),/宽带账号和密码/);
const two={lan:{device:'br-lan'},bridge:{'.name':'br','ports':['eth0','eth1']},wan:{proto:'dhcp'}};
const dhcp=plan({...base,mode:'dhcp'},two,['eth0','eth1']);
assert(dhcp.some(x=>x[2]==='br'&&x[3]==='ports'&&x[4].join()==='eth0'));
assert(dhcp.some(x=>x[2]==='wan'&&x[3]==='proto'&&x[4]==='dhcp'));
const pp=plan({...base,mode:'pppoe'},two,['eth0','eth1']);
assert(pp.some(x=>x[2]==='wan'&&x[3]==='username'&&x[4]==='u'));
console.log('Setup wizard: single-LAN routing, DHCP isolation, subnet/IP checks, WAN separation and PPPoE validation passed');
